# ============================================================================
# NORMALIZATION
# ============================================================================

def rank_normalize(score):
    """
    Convert arbitrary score map into percentile/rank space.

    Higher score = better candidate.
    """

    score = np.asarray(
        score,
        dtype=np.float32,
    )

    flat = score.reshape(-1)

    order = np.argsort(
        np.argsort(flat)
    )

    if len(flat) <= 1:
        return np.zeros_like(
            score,
            dtype=np.float32,
        )

    ranked = (
        order.astype(
            np.float32
        )
        /
        float(
            len(flat) - 1
        )
    )

    return ranked.reshape(
        score.shape
    )


# ============================================================================
# IMAGE CONTEXT
# ============================================================================

def centered_context(
    image,
    cx,
    cy,
    size,
):
    """
    Extract a context patch centered on a known candidate location.

    Used ONLY during candidate scoring.

    During candidate generation, candidate coordinates are generated by
    sliding the context over the search image.
    """

    half = size // 2

    x0 = int(round(cx)) - half
    y0 = int(round(cy)) - half

    x1 = x0 + size
    y1 = y0 + size

    if (
        x0 < 0
        or y0 < 0
        or x1 > image.shape[1]
        or y1 > image.shape[0]
    ):
        return None

    return image[
        y0:y1,
        x0:x1,
    ]


# ============================================================================
# TEMPLATE RESIZING
# ============================================================================

def resize_template(
    template,
    size,
):
    """
    Create a context template by resizing the canonical 10x10 observation.

    IMPORTANT:
    This is not a new physical renderer.

    It is only a controlled image-space context experiment.
    """

    if size == BASE_TEMPLATE_SIZE:
        return template.astype(
            np.float32
        )

    return cv2.resize(
        template.astype(
            np.float32
        ),
        (
            size,
            size,
        ),
        interpolation=cv2.INTER_CUBIC,
    )


# ============================================================================
# MULTI-SCALE NCC
# ============================================================================

def ncc_at_scale(
    search,
    template,
    size,
):
    """
    NCC using a scale/context-specific template.
    """

    t = resize_template(
        template,
        size,
    )

    # Avoid templates larger than the search image.
    if (
        t.shape[0] > search.shape[0]
        or
        t.shape[1] > search.shape[1]
    ):
        raise ValueError(
            "Template larger than search."
        )

    return cv2.matchTemplate(
        search.astype(
            np.float32
        ),
        t.astype(
            np.float32
        ),
        cv2.TM_CCOEFF_NORMED,
    )


# ============================================================================
# MULTI-SCALE GRADIENT
# ============================================================================

def gradient_magnitude(
    image,
):
    image = image.astype(
        np.float32
    )

    gx = cv2.Sobel(
        image,
        cv2.CV_32F,
        1,
        0,
        ksize=3,
    )

    gy = cv2.Sobel(
        image,
        cv2.CV_32F,
        0,
        1,
        ksize=3,
    )

    return np.sqrt(
        gx * gx
        +
        gy * gy
    )


def gradient_ncc_at_scale(
    search,
    template,
    size,
):
    search_gradient = gradient_magnitude(
        search
    )

    template_gradient = gradient_magnitude(
        resize_template(
            template,
            size,
        )
    )

    return cv2.matchTemplate(
        search_gradient,
        template_gradient,
        cv2.TM_CCOEFF_NORMED,
    )


# ============================================================================
# MAP ALIGNMENT
# ============================================================================

def map_to_common_coordinates(
    score_map,
    template_size,
):
    """
    matchTemplate returns coordinates corresponding to the template's
    top-left corner.

    Convert to candidate center coordinates so different context sizes
    can be compared in the same physical coordinate system.
    """

    h, w = score_map.shape

    yy, xx = np.indices(
        (h, w)
    )

    center_x = (
        xx
        +
        template_size / 2.0
    )

    center_y = (
        yy
        +
        template_size / 2.0
    )

    return (
        center_x,
        center_y,
    )


def remap_to_search_grid(
    score_map,
    template_size,
):
    """
    Put a match score map back onto the full search coordinate grid.

    Pixels without valid template support receive -inf.

    The resulting grid represents candidate CENTER coordinates.
    """

    full = np.full(
        (
            SEARCH_H,
            SEARCH_W,
        ),
        -np.inf,
        dtype=np.float32,
    )

    h, w = score_map.shape

    half = template_size / 2.0

    for y in range(h):
        cy = int(
            round(
                y + half
            )
        )

        if cy < 0 or cy >= SEARCH_H:
            continue

        x0 = int(
            round(
                half
            )
        )

        x1 = min(
            SEARCH_W,
            int(
                round(
                    w + half
                )
            ),
        )

        if x1 <= x0:
            continue

        full[
            cy,
            x0:x1,
        ] = score_map[
            y,
            :x1 - x0,
        ]

    return full


# ============================================================================
# TOP-K CANDIDATES
# ============================================================================

def extract_topk(
    score_map,
    K,
):
    """
    Spatially separated top-K candidate centers.
    """

    valid = np.isfinite(
        score_map
    )

    if not np.any(valid):
        return []

    work = score_map.copy()

    work[
        ~valid
    ] = -np.inf

    flat = work.reshape(-1)

    raw_k = min(
        flat.size,
        max(
            20 * K,
            100,
        ),
    )

    idx = np.argpartition(
        flat,
        -raw_k,
    )[-raw_k:]

    idx = idx[
        np.argsort(
            flat[idx]
        )[::-1]
    ]

    selected = []

    suppression_radius = 3.0
    radius2 = (
        suppression_radius
        *
        suppression_radius
    )

    for i in idx:

        if not np.isfinite(
            flat[i]
        ):
            continue

        y, x = np.unravel_index(
            int(i),
            work.shape,
        )

        good = True

        for sx, sy in selected:

            dx = (
                x - sx
            )

            dy = (
                y - sy
            )

            if (
                dx * dx
                +
                dy * dy
                <= radius2
            ):
                good = False
                break

        if good:

            selected.append(
                (
                    int(x),
                    int(y),
                )
            )

            if len(selected) >= K:
                break

    return selected


# ============================================================================
# CANDIDATE EVALUATION
# ============================================================================

def evaluate_candidates(
    candidates,
):
    if not candidates:
        return (
            np.inf,
            -1,
        )

    errors = []

    for x, y in candidates:

        dx = (
            float(x)
            -
            TARGET_SEARCH_X
        )

        dy = (
            float(y)
            -
            TARGET_SEARCH_Y
        )

        errors.append(
            np.sqrt(
                dx * dx
                +
                dy * dy
            )
        )

    errors = np.asarray(
        errors,
        dtype=np.float32,
    )

    best = int(
        np.argmin(
            errors
        )
    )

    return (
        float(
            errors[best]
        ),
        best + 1,
    )


# ============================================================================
# CROSS-SCALE FUSION
# ============================================================================

def fuse_maps(
    maps,
    weights=None,
):
    """
    Rank-normalized weighted fusion.

    Each map is converted to rank space before fusion.

    This prevents raw score scales from dominating.
    """

    if weights is None:
        weights = [
            1.0
            for _ in maps
        ]

    normalized = [
        rank_normalize(
            m
        )
        for m in maps
    ]

    total_weight = sum(
        weights
    )

    fused = np.zeros_like(
        normalized[0],
        dtype=np.float32,
    )

    for m, w in zip(
        normalized,
        weights,
    ):
        fused += (
            m
            *
            float(w)
        )

    fused /= max(
        total_weight,
        1e-12,
    )

    return fused


# ============================================================================
# CANONICAL OBSERVATION
# ============================================================================

def load_scene(
    scene_type,
    seed,
):
    """
    Strictly use canonical renderer.
    """

    search = cr.render_search(
        TARGET_X,
        TARGET_Y,
        scene_type,
        seed,
    )

    reference = cr.render_reference(
        TARGET_X,
        TARGET_Y,
        scene_type,
        seed,
    )

    template = cr.create_ps02_template(
        reference
    )

    search = np.asarray(
        search
    )

    template = np.asarray(
        template
    )

    if search.ndim == 3:
        search = cv2.cvtColor(
            search,
            cv2.COLOR_BGR2GRAY,
        )

    if template.ndim == 3:
        template = cv2.cvtColor(
            template,
            cv2.COLOR_BGR2GRAY,
        )

    return (
        search.astype(
            np.float32
        ),
        template.astype(
            np.float32
        ),
    )


